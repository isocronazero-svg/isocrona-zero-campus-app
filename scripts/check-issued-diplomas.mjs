function buildDiplomaCode(course, memberId) {
  return `IZ-${course.startDate.slice(0, 4)}-${course.id.split("-")[1]}-${memberId.split("-")[1]}`;
}

async function assertIssuedDiplomaSurvivesAutomation(baseUrl) {
  const admin = createJsonClient("admin", baseUrl);
  const login = await admin.post("/api/login", {
    email: "admin@isocronazero.org",
    password: "campus123"
  });
  assert.equal(login.body?.ok, true, "El login admin debe funcionar");

  const initialStateResponse = await admin.get("/api/state");
  const initialState = initialStateResponse.body;
  const memberId = "member-1";
  const courseId = "course-pub02";
  const controlledCourse = buildControlledCourse(courseId, memberId);
  const diplomaCode = buildDiplomaCode(controlledCourse, memberId);

  initialState.members = (initialState.members || []).map((member) =>
    member.id === memberId ? { ...member, dni: "12345678A" } : member
  );
  initialState.courses = [
    ...(initialState.courses || []).filter((course) => course.id !== courseId),
    controlledCourse
  ];

  const saveIssuedState = await admin.post("/api/state", initialState);
  assert.equal(saveIssuedState.body?.ok, true, "El estado con el curso controlado debe guardarse");

  const emittedStateResponse = await admin.get("/api/state");
  const emittedCourse = (emittedStateResponse.body?.courses || []).find((course) => course.id === courseId);
  assert.ok(emittedCourse?.diplomaReady?.includes(memberId), "La automatizacion debe emitir el diploma controlado");

  const firstVerify = await admin.get(`/api/verify?code=${encodeURIComponent(diplomaCode)}`);
  assert.equal(firstVerify.body?.ok, true, "El diploma emitido debe verificarse publicamente");
  assert.equal(firstVerify.body?.diploma?.code, diplomaCode, "La verificacion debe devolver el mismo codigo emitido");

  const degradedState = emittedStateResponse.body;
  const degradedCourse = (degradedState.courses || []).find((course) => course.id === courseId);
  degradedCourse.attendance[memberId] = 0;
  degradedCourse.evaluations[memberId] = "No apto";
  degradedCourse.diplomaReady = [];

  const saveDegradedState = await admin.post("/api/state", degradedState);
  assert.equal(saveDegradedState.body?.ok, true, "El estado degradado debe guardarse");

  const automationRun = await admin.post("/api/automation/run", {});
  assert.equal(automationRun.body?.ok, true, "La automatizacion manual debe ejecutarse");

  const finalStateResponse = await admin.get("/api/state");
  const finalCourse = (finalStateResponse.body?.courses || []).find((course) => course.id === courseId);
  assert.ok(
    finalCourse?.diplomaReady?.includes(memberId),
    "Un diploma ya emitido debe seguir en diplomaReady tras degradar requisitos y ejecutar automatizacion"
  );

  const secondVerify = await admin.get(`/api/verify?code=${encodeURIComponent(diplomaCode)}`);
  assert.equal(secondVerify.body?.ok, true, "El mismo codigo debe seguir verificando tras la automatizacion");
  assert.equal(secondVerify.body?.diploma?.code, diplomaCode, "La verificacion debe conservar el codigo original");
}

async function main() {
  const port = await getAvailablePort();
  const baseUrl = `http://127.0.0.1:${port}`;
  const server = startServer(port, baseUrl);

  try {
    await waitForServer(baseUrl);
    await assertIssuedDiplomaSurvivesAutomation(baseUrl);
    console.log("Issued diplomas preservation check passed.");
  } finally {
    await stopServer(server);
    rmSync(tempRoot, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
