import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";
import net from "node:net";
import os from "node:os";
import path from "node:path";
import vm from "node:vm";

const require = createRequire(import.meta.url);
const { buildActivityCertificate, buildActivityCertificatePages } = require("../server/activity-certificate");
const repo = fileURLToPath(new URL("..", import.meta.url));
const code = readFileSync(new URL("../server.js", import.meta.url), "utf8");
function source(text, name) {
  const start = text.indexOf(`function ${name}(`);
  const end = text.indexOf("\nfunction ", start + 1);
  assert.ok(start >= 0);
  return text.slice(start, end < 0 ? undefined : end);
}
const context = vm.createContext({ Buffer });
vm.runInContext(`${source(code, "buildPdfDocument")}\n${source(code, "escapePdfText")}`, context);
// Existing one-page diplomas must retain exactly the same PDF bytes.
assert.equal(createHash("sha256").update(context.buildPdfDocument("BT (QA) Tj ET")).digest("hex"),
  "c543af6a1743ea615a33e858ae51205573fb47b8e9880966de4042356aee1eae");

const seed = JSON.parse(readFileSync(new URL("../data/default-state.json", import.meta.url), "utf8"));
const password = randomUUID();
seed.accounts = ["admin", "member", "other", "instructor"].map(id => ({ id, name: id, email: `${id}@example.test`,
  role: ["admin", "instructor"].includes(id) ? id : "member", memberId: id, password }));
seed.members = seed.accounts.map(a => ({ id: a.id, name: a.name, email: a.email }));
seed.associates = [];
seed.settings.automation = { autoRunOnSave: false, autoGenerateDiplomas: false, autoSendDiplomas: false };
seed.courses = Array.from({ length: 32 }, (_, i) => ({ id: `course-${i}`, title: `Actividad ${i} (QA)`, type: i % 2 ? "Jornada" : "Curso",
  hours: i % 2 ? 1.5 : 2, startDate: "2025-01-01", endDate: "2025-02-01", diplomaReady: ["member"], enrolledIds: ["member"] }));
seed.courses.push({ id: "pending", title: "Pending must not count", hours: 99, enrolledIds: ["member"], diplomaReady: [] });
seed.courses.push({ id: "foreign", title: "Foreign private activity", hours: 88, diplomaReady: ["instructor"] });
const model = buildActivityCertificate(seed, "member");
assert.equal(model.activities.length, 32);
assert.equal(model.totalHours, 56);
assert.equal(buildActivityCertificate(seed, "absent"), null);
assert.equal(buildActivityCertificate(seed, "other").activities.length, 0);
const dirty = structuredClone(seed);
dirty.courses.push(dirty.courses[0], { id: "invalid", hours: "NaN", diplomaReady: ["member"] });
assert.equal(buildActivityCertificate(dirty, "member").totalHours, 56);
assert.equal(buildActivityCertificate(dirty, "member").activities.length, 33);
const pages = buildActivityCertificatePages(model, context.escapePdfText);
assert.ok(pages.length > 1);
assert.match(pages.join(""), /Actividad 31/);
assert.match(pages.join(""), /TOTAL ACUMULADO: 56/);
assert.ok(pages.join("").includes("\\(QA\\)"));
const malicious = buildActivityCertificatePages({ ...model, name: "QA\u0129\nendstream", activities: [] }, context.escapePdfText).join("");
assert.match(malicious, /QA\? endstream/);
const longPages = buildActivityCertificatePages({ ...model, activities: [{ ...model.activities[0], title: "X".repeat(8000) }] }, context.escapePdfText);
assert.ok(longPages.length > 1);
assert.ok(longPages.every(page => !/48 -\d+ Td/.test(page)));

const root = mkdtempSync(path.join(os.tmpdir(), "iz-activity-certificate-"));
writeFileSync(path.join(root, "seed.json"), JSON.stringify(seed));
const port = await new Promise(resolve => { const probe = net.createServer(); probe.listen(0, "127.0.0.1", () => {
  const value = probe.address().port; probe.close(() => resolve(value));
}); });
const base = `http://127.0.0.1:${port}`;
let child, logs = "";
const route = "/api/member/activity-certificate.pdf";
async function login(id) {
  const response = await fetch(base + "/api/login", { method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email: `${id}@example.test`, password }) });
  assert.equal(response.status, 200);
  return response.headers.get("set-cookie").split(";")[0];
}
try {
  const env = { ...process.env, NODE_ENV: "test", DATABASE_URL: "", HOST: "127.0.0.1", PORT: String(port),
    IZ_DATA_DIR: path.join(root, "data"), IZ_DEFAULT_STATE_PATH: path.join(root, "seed.json"), IZ_BASE_URL: base,
    IZ_BOOTSTRAP_ADMIN_EMAIL: "", IZ_BOOTSTRAP_ADMIN_PASSWORD: "", AUTOMATION_INTERVAL_MS: "86400000" };
  for (const key of Object.keys(env)) if (key.startsWith("SMTP_")) env[key] = "";
  child = spawn(process.execPath, ["server.js"], { cwd: repo, env, stdio: ["ignore", "pipe", "pipe"] });
  child.stdout.on("data", b => logs += b); child.stderr.on("data", b => logs += b);
  let ready = false;
  for (let i = 0; i < 100; i++) {
    try { if ((await fetch(base + "/healthz")).ok) { ready = true; break; } } catch {}
    if (child.exitCode !== null) break;
    await delay(50);
  }
  assert.ok(ready, logs);
  assert.equal((await fetch(base + route)).status, 401);
  const member = await login("member"), admin = await login("admin"), instructor = await login("instructor"), other = await login("other");
  for (const [cookie, query, status] of [[member, "", 200], [member, "?memberId=instructor", 403],
    [instructor, "?memberId=member", 403], [admin, "?memberId=member", 200], [other, "", 404]]) {
    const response = await fetch(base + route + query, { headers: { Cookie: cookie } });
    assert.equal(response.status, status, query);
    if (status === 200) {
      assert.equal(response.headers.get("content-type"), "application/pdf");
      assert.match(response.headers.get("cache-control"), /no-store/);
      const pdf = Buffer.from(await response.arrayBuffer());
      assert.match(pdf.toString("latin1"), /^%PDF-1.4/);
      assert.match(pdf.toString("latin1"), /TOTAL ACUMULADO: 56/);
      assert.doesNotMatch(pdf.toString("latin1"), /Foreign private activity|Pending must not count/);
      if (process.env.IZ_QA_CERT_OUTPUT) writeFileSync(process.env.IZ_QA_CERT_OUTPUT, pdf);
    }
  }
  const download = await fetch(base + route + "?download=1", { headers: { Cookie: member } });
  assert.match(download.headers.get("content-disposition"), /^attachment;/);
  const view = await fetch(base + route, { headers: { Cookie: member } });
  assert.match(view.headers.get("content-disposition"), /^inline;/);
  const app = readFileSync(new URL("../public/app.js", import.meta.url), "utf8");
  assert.match(source(app, "renderMemberDiplomas"), /Descargar PDF acumulado/);
  console.log("Activity certificate checks passed (ownership, totals, issued-only, pagination, PDF escaping and download).");
} finally {
  if (child && child.exitCode === null) await new Promise(resolve => { child.once("exit", resolve); child.kill(); });
  rmSync(root, { recursive: true, force: true });
}
