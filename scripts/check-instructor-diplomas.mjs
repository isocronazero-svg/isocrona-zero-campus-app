async function stop() {
  if (child && child.exitCode === null) await new Promise(resolve => { child.once("exit", resolve); child.kill(); });
}
async function request(url, cookie = "", method = "GET", body) {
  return fetch(base + url, { method, headers: { Cookie: cookie, "Content-Type": "application/json" },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
}
async function json(url, cookie, method, body, status = 200) {
  const response = await request(url, cookie, method, body);
  const result = await response.json();
  assert.equal(response.status, status, JSON.stringify(result));
  return result;
}
